const grid = document.querySelector(".filmid_grid");
const popup = document.getElementById("popup");
const title = document.getElementById("p_title");
const rating = document.getElementById("p_rating");
const description = document.getElementById("p_description");
const arvamus = document.getElementById("p_arvamus");
const image = document.getElementById("p_img");
const parimad_grid = document.querySelector(".parimad_grid");
function closepopup(){
  if (popup) {
    popup.classList.add("invis");
  }
}

function Moviekaart(id, movie) {
  const numericRating = movie.rating.split("/")[0].trim();

  const card = document.createElement("div");
  card.className = "filmid_kaart";
  card.dataset.id = id;

  card.innerHTML = `
    <img class="film_poster" src="posters/${movie.img}" alt="${movie.title} poster">
    <div class="film_intro">
      <h2 class="filmi_pealkiri">${movie.title}</h2>
      <p class="film_info">${movie.year} - ${movie.genre} - ${numericRating}</p>
      <p class="filmi_kirjeldus">${movie.short}</p>
    </div>
    `;

  card.addEventListener("click", () => {
    title.textContent = movie.title;
    description.textContent = movie.description;
    rating.textContent = movie.rating;
    arvamus.textContent = movie.opinion;
    image.src = `posters/${movie.img}`;
    image.alt = `${movie.title} poster`;
    popup.classList.remove("invis");
  });
    return card;
}

Object.entries(movie_id).forEach(([id, movie]) => {
  if (grid) {
    grid.appendChild(Moviekaart(id, movie));
  }
  if (parimad_grid && movie.parimad === 1) {
    parimad_grid.appendChild(Moviekaart(id,movie))
  }
});

if (popup) {
  popup.addEventListener("click", (event) => {
    if (event.target === popup) {
      closepopup();
    }
  });
}
if (popup) {
  document.addEventListener("keydown", (event) => {
    if (event.key == "Escape") {
      closepopup();
    }
  });
}